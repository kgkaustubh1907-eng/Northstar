import axios from 'axios';
const api=axios.create({baseURL:import.meta.env.VITE_API_URL||(import.meta.env.DEV?'http://localhost:8000/api':'/api'),headers:{'Content-Type':'application/json'}});
api.interceptors.request.use(c=>{const token=localStorage.getItem('access');if(token)c.headers.Authorization=`Token ${token}`;return c});
const dataPath=/^\/(patients|employees|departments|diagnoses|tests|equipment|prescriptions|medical-stores|people|caretakers)(\/|$)/;
api.interceptors.response.use(r=>{const method=(r.config.method||'get').toLowerCase();if(['post','put','patch','delete'].includes(method)&&dataPath.test(new URL(r.config.url,window.location.origin).pathname.replace('/api',''))){window.dispatchEvent(new CustomEvent('hospital:data-changed',{detail:{method,url:r.config.url}}))}return r},error=>{if(error.response?.status===401){localStorage.removeItem('access');localStorage.removeItem('refresh');if(location.pathname!=='/login')location.href='/login'}return Promise.reject(error)});
const list=async(path,params)=>{const d=(await api.get(path,{params})).data;return d.results??d};
export const getPatients=params=>list('/patients/',params);
export const createPatient=data=>api.post('/patients/',data).then(r=>r.data);
export const updatePatient=(id,data)=>api.patch(`/patients/${id}/`,data).then(r=>r.data);
export const deletePatient=id=>api.delete(`/patients/${id}/`);
export const getPatient=id=>api.get(`/patients/${id}/`).then(r=>r.data);
export const getPatientHistory=id=>api.get(`/patients/${id}/history/`).then(r=>r.data);
export const getDoctors=params=>api.get('/employees/',{params:{...params,search:params?.search||''}}).then(r=>r.data.results??r.data);
export const getDoctor=id=>api.get(`/employees/${id}/`).then(r=>r.data);
export const getDepartments=()=>list('/departments/');
export const getDiagnoses=()=>list('/diagnoses/');
export const createDiagnosis=data=>api.post('/diagnoses/',data).then(r=>r.data);
export const getTests=()=>list('/tests/');
export const createTest=data=>api.post('/tests/',data).then(r=>r.data);
export const updateTest=(id,data)=>api.patch(`/tests/${id}/`,data).then(r=>r.data);
export const getEquipment=()=>list('/equipment/');
export const createEquipment=data=>api.post('/equipment/',data).then(r=>r.data);
export const updateEquipment=(id,data)=>api.patch(`/equipment/${id}/`,data).then(r=>r.data);
export const deleteEquipment=id=>api.delete(`/equipment/${id}/`);
export const getPrescriptions=()=>list('/prescriptions/');
export const createPrescription=data=>api.post('/prescriptions/',data).then(r=>r.data);
export const searchHospital=query=>api.post('/query/',{query}).then(r=>r.data);
export const getDashboard=()=>api.get('/dashboard/').then(r=>r.data);
export const getDataRevision=()=>api.get('/changes/').then(r=>r.data.revision);
export const getPeople=()=>list('/people/');
export const createPerson=data=>api.post('/people/',data).then(r=>r.data);
export const getCaretakers=()=>list('/caretakers/');
export const createCaretaker=data=>api.post('/caretakers/',data).then(r=>r.data);
export const getMedicalStores=()=>list('/medical-stores/');
export const getGlobalSearch=q=>api.get('/search/',{params:{q}}).then(r=>r.data.results);
export const login=async(username,password)=>{const {data}=await api.post('/auth/token/',{username,password});localStorage.setItem('access',data.access);localStorage.setItem('refresh',data.refresh);const me=await api.get('/auth/me/');return me.data};
export const getMe=()=>api.get('/auth/me/').then(r=>r.data);
export const logout=()=>{localStorage.removeItem('access');localStorage.removeItem('refresh')};
export default api;
